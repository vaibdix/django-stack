package scaffold

import (
	"fmt"
	"strings"
)

func (e *Env) applyRuff(projectPath string) error {
	metadata := e.pythonToolingMetadata()
	pe := NewPyprojectEditor(projectPath, e.Cfg.ProjectName, metadata)

	if !pe.Contains("[tool.ruff]") {
		firstParty := []string{fmt.Sprintf(`"%s"`, e.Cfg.ModuleName())}
		if e.Cfg.AppName != "" {
			firstParty = append(firstParty, fmt.Sprintf(`"%s"`, e.Cfg.AppName))
		}

		pe.AppendSection(fmt.Sprintf(`[tool.ruff]
target-version = "%s"
line-length = 120

[tool.ruff.lint]
# Ruff's defaults are E4/E7/E9, F, B, UP and RUF; extend-select adds to them
# rather than replacing them, so new default rules arrive with new releases.
extend-select = [
    "A",
    "ANN",
    "ARG",
    "C4",
    "DJ",
    "DTZ",
    "E",
    "EM",
    "ERA",
    "I",
    "LOG",
    "N",
    "PL",
    "PTH",
    "RET",
    "S",
    "SIM",
    "TC",
    "TID",
    "TRY",
    "W",
]
ignore = ["SIM102"]

[tool.ruff.lint.per-file-ignores]
# Split settings modules are built on "from .base import *", which is the
# documented Django pattern. F403 flags the star import and F405 flags every
# name that comes through it, so both have to be off here — otherwise names
# like env and BASE_DIR are reported as possibly undefined in each file.
# The star import also carries a noqa, which this configuration makes
# redundant but a project without these per-file ignores still needs.
"*/settings/*.py" = ["F403", "F405", "RUF100"]
"**/models.py" = ["RUF012"]
"**/forms.py" = ["RUF012"]
"**/admin.py" = ["RUF012"]
"**/api.py" = ["RUF012", "ARG002"]
"**/api/*.py" = ["RUF012", "ARG002"]
"**/management/commands/*.py" = ["ARG002"]
# DEBUG is a Django setting name, so the property that derives it keeps that
# spelling; N802 would otherwise demand debug() and break every reader.
"**/conf.py" = ["N802"]
# manage.py is written by django-admin; its deferred import and error message
# are the documented form.
"manage.py" = ["PLC0415", "TRY003", "EM101"]
# Django calls a context processor with the request whether it reads it or not.
"**/context_processors.py" = ["ARG001"]
# Django dictates the signature of a view and of an error handler; the request
# and the exception are passed whether the handler reads them or not.
"**/views.py" = ["ARG001", "RUF012"]
# assert is how Django's TestCase reports failures.
"**/tests*.py" = ["S101", "RUF012"]
"**/tests/*.py" = ["S101", "RUF012"]
# Migrations are generated by Django; they are not ours to restyle.
"**/migrations/*.py" = ["ALL"]

[tool.ruff.lint.isort]
force-single-line = true
known-first-party = [%s]
`, metadata.RuffTargetVersion, strings.Join(firstParty, ", ")))
	}

	if err := pe.Save(); err != nil {
		return err
	}

	e.Step("Ruff linter configured in pyproject.toml")
	return nil
}
