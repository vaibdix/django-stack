func (e *Env) applyRuff(projectPath string) error {
	metadata := e.pythonToolingMetadata()
	pe, err := newPyprojectEditor(projectPath, e.cfg.ProjectName, metadata)
	if err != nil {
		return err
	}

	if !pe.Contains("[tool.ruff]") {
		firstParty := []string{
			fmt.Sprintf(`"%s"`, e.cfg.ModuleName()),
			fmt.Sprintf(`"%s"`, coreApp),
			fmt.Sprintf(`"%s"`, accountsApp),
		}
		if e.cfg.AppName != "" {
			firstParty = append(firstParty, fmt.Sprintf(`"%s"`, e.cfg.AppName))
		}

		pe.AppendSection(fmt.Sprintf(`[tool.ruff]
target-version = "%s"
line-length = 120

[tool.ruff.lint]
# Ruff's defaults are E4/E7/E9, F, B, UP and RUF; extend-select adds to them
# rather than replacing them, so new default rules arrive with new releases.
extend-select = [
    "A",
    "ANN",
    "ARG",
    "C4",
    "DJ",
    "DTZ",
    "E",
    "EM",
    "ERA",
    "I",
    "LOG",
    "N",
    "PL",
    "PTH",
    "RET",
    "S",
    "SIM",
    "TC",
    "TID",
    "TRY",
    "W",
]
ignore = ["SIM102"]

[tool.ruff.lint.per-file-ignores]
# Split settings modules are built on "from .base import *", which is the
# documented Django pattern. F403 flags the star import and F405 flags every
# name that comes through it, so both have to be off here — otherwise names
# like env and BASE_DIR are reported as possibly undefined in each file.
# The star import also carries a noqa, which this configuration makes
# redundant but a project without these per-file ignores still needs.
"*/settings/*.py" = ["F403", "F405", "RUF100"]
"**/models.py" = ["RUF012"]
"**/forms.py" = ["RUF012"]
"**/admin.py" = ["RUF012"]
"**/api.py" = ["RUF012", "ARG002"]
# django-ninja passes the request to every operation as its first argument,
# whether the body reads it or not, so ARG001 is reported for each write
# endpoint that only needs its path parameter.
"**/api/*.py" = ["RUF012", "ARG002", "ARG001"]
"**/management/commands/*.py" = ["ARG002"]
# DEBUG is a Django setting name, so the property that derives it keeps that
# spelling; N802 would otherwise demand debug() and break every reader.
"**/conf.py" = ["N802"]
# manage.py is written by django-admin; its deferred import and error message
# are the documented form.
"manage.py" = ["PLC0415", "TRY003", "EM101"]
# Django calls a context processor with the request whether it reads it or not.
"**/context_processors.py" = ["ARG001"]
# Django dictates the signature of a view and of an error handler; the request
# and the exception are passed whether the handler reads them or not.
"**/views.py" = ["ARG001", "RUF012"]
# assert is how Django's TestCase reports failures.
"**/tests*.py" = ["S101", "RUF012"]
"**/tests/*.py" = ["S101", "RUF012"]
# Migrations are generated by Django; they are not ours to restyle.
"**/migrations/*.py" = ["ALL"]

[tool.ruff.lint.isort]
force-single-line = true
known-first-party = [%s]
%s`, metadata.RuffTargetVersion, strings.Join(firstParty, ", "), e.runtimeEvaluatedSection()))
	}

	if err := pe.Save(); err != nil {
		return err
	}

	e.Step("Ruff linter configured in pyproject.toml")
	return nil
}

func (e *Env) runtimeEvaluated() (bases, decorators []string) {
	if e.usesPydanticModels() {
		bases = append(bases, "pydantic.BaseModel")
	}
	if e.cfg.SetupPydanticConf {
		bases = append(bases, "pydantic_settings.BaseSettings")
	}
	if e.cfg.SetupNinja {
		bases = append(bases, "ninja.Schema")
		for _, method := range []string{"get", "post", "put", "patch", "delete"} {
			decorators = append(decorators, "ninja.Router."+method)
		}
		decorators = append(decorators, "ninja.NinjaAPI.exception_handler")
	}
	return bases, decorators
}

func tomlStringArray(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func (e *Env) runtimeEvaluatedSection() string {
	bases, decorators := e.runtimeEvaluated()
	if len(bases) == 0 && len(decorators) == 0 {
		return ""
	}
	section := `
[tool.ruff.lint.flake8-type-checking]
# These classes and decorators read annotations at runtime, so the imports the
# annotations name stay real imports rather than moving under "if TYPE_CHECKING:".
runtime-evaluated-base-classes = ` + tomlStringArray(bases) + "\n"
	if len(decorators) > 0 {
		section += "runtime-evaluated-decorators = " + tomlStringArray(decorators) + "\n"
	}
	return section
}

func (e *Env) lazyAnnotations() bool {
	_, minor, ok := strings.Cut(e.pythonToolingMetadata().MypyPythonVersion, ".")
	if !ok {
		return false
	}
	number, err := strconv.Atoi(minor)
	return err == nil && number >= 14
}

func (e *Env) typingImportCommands() []formattingCommand {
	if !e.lazyAnnotations() {
		return nil
	}
	bases, decorators := e.runtimeEvaluated()
	return []formattingCommand{{
		Stage:  "ruff typing-only imports",
		Module: "ruff",
		Args: []string{
			"check", "--fix-only", "--unsafe-fixes", "--select", "TC001,TC002,TC003",
			"--target-version", e.pythonToolingMetadata().RuffTargetVersion,
			"--config", "lint.flake8-type-checking.runtime-evaluated-base-classes = " + tomlStringArray(bases),
			"--config", "lint.flake8-type-checking.runtime-evaluated-decorators = " + tomlStringArray(decorators),
			".",
		},
	}}
}
