package assets

// tailwindBaseTemplateContent returns the Tailwind app shell.
//
// The structure is the framed column: a fixed-width centre with a rule down
// each side, a sticky header, the page body, and a two-up closing band. The
// .frame and .ticks classes are defined in the generated project's
// tailwind-source.css, because they are structure rather than a utility stack.
