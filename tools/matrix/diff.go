package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var (
	skipDirs = []string{".venv", "node_modules", ".git", "__pycache__", ".mypy_cache", ".ruff_cache", ".pytest_cache", "staticfiles"}
	skipFile = []string{"db.sqlite3", ".DS_Store"}
	masks    = []string{
		`SECRET_KEY=.*`,
		`(DB_PASSWORD|DB_ROOT_PASSWORD|POSTGRES_PASSWORD|MYSQL_PASSWORD|MYSQL_ROOT_PASSWORD)=.*`,
		`DB_PORT=[0-9]+`,
		`127\.0\.0\.1:[0-9]+:`,
		`"createdAt": *"[^"]*"`,
		`"version": *"sweep-[0-9a-f]+"`,
		`Generated by Django [0-9.]+ on [0-9-]+ [0-9:]+`,
	}
	maskPatterns = compileMasks()
)

type diffResult struct {
	OnlyBaseline []string `json:"onlyBaseline,omitempty"`
	OnlyRun      []string `json:"onlyRun,omitempty"`
	Changed      []string `json:"changed,omitempty"`
	Missing      bool     `json:"missing,omitempty"`
}

func (d diffResult) empty() bool {
	return len(d.OnlyBaseline) == 0 && len(d.OnlyRun) == 0 && len(d.Changed) == 0 && !d.Missing
}

func compileMasks() []*regexp.Regexp {
	out := make([]*regexp.Regexp, len(masks))
	for i, m := range masks {
		out[i] = regexp.MustCompile(m)
	}
	return out
}

func runDiff(ctx context.Context, args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("diff", flag.ContinueOnError)
	dir := fs.String("run", "", "run folder to compare")
	baseline := fs.String("baseline", "", "baseline run folder")
	only := fs.String("only", "", "comma-separated project names (default: all)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	r, err := openRun(*dir)
	if err != nil {
		return err
	}
	base, err := openRun(*baseline)
	if err != nil {
		return err
	}
	projects, err := r.only(*only)
	if err != nil {
		return err
	}
	differing := 0
	for _, p := range projects {
		res, patch := diffProject(ctx, base.projectDir(p.Name), r.projectDir(p.Name))
		_ = writeJSON(filepath.Join(r.logDir(p.Name), "diff.json"), res)
		_ = os.WriteFile(filepath.Join(r.logDir(p.Name), "diff.patch"), patch, 0o644)
		if !res.empty() {
			differing++
			_, _ = fmt.Fprintf(stdout, "%-28s changed=%d only-baseline=%d only-run=%d missing=%t\n",
				p.Name, len(res.Changed), len(res.OnlyBaseline), len(res.OnlyRun), res.Missing)
		}
	}
	_, _ = fmt.Fprintf(stdout, "%d of %d projects differ from %s\n", differing, len(projects), *baseline)
	return nil
}

func diffProject(ctx context.Context, baseDir, runDir string) (diffResult, []byte) {
	var res diffResult
	baseFiles, baseErr := listTree(baseDir)
	runFiles, runErr := listTree(runDir)
	if baseErr != nil || runErr != nil {
		res.Missing = (baseErr != nil) != (runErr != nil)
		return res, nil
	}
	var patch bytes.Buffer
	for _, rel := range baseFiles {
		if !slices.Contains(runFiles, rel) {
			res.OnlyBaseline = append(res.OnlyBaseline, rel)
			continue
		}
		a, errA := os.ReadFile(filepath.Join(baseDir, rel))
		b, errB := os.ReadFile(filepath.Join(runDir, rel))
		if errA != nil || errB != nil || !bytes.Equal(mask(a), mask(b)) {
			res.Changed = append(res.Changed, rel)
			patch.Write(gitDiff(ctx, filepath.Join(baseDir, rel), filepath.Join(runDir, rel)))
		}
	}
	for _, rel := range runFiles {
		if !slices.Contains(baseFiles, rel) {
			res.OnlyRun = append(res.OnlyRun, rel)
		}
	}
	return res, patch.Bytes()
}

func listTree(root string) ([]string, error) {
	if _, err := os.Stat(root); err != nil {
		return nil, err
	}
	var files []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if path != root && slices.Contains(skipDirs, d.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if slices.Contains(skipFile, d.Name()) || !d.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		files = append(files, rel)
		return nil
	})
	slices.Sort(files)
	return files, err
}

func mask(data []byte) []byte {
	for _, re := range maskPatterns {
		data = re.ReplaceAll(data, []byte("<masked>"))
	}
	return data
}

func gitDiff(ctx context.Context, a, b string) []byte {
	args := []string{"diff", "--no-index", "--no-color"}
	for _, m := range masks {
		args = append(args, "-I", m)
	}
	out, _ := exec.CommandContext(ctx, "git", append(args, a, b)...).Output()
	if len(bytes.TrimSpace(out)) == 0 {
		return []byte(fmt.Sprintf("binary or masked-only difference: %s\n", strings.TrimPrefix(b, "/")))
	}
	return out
}
