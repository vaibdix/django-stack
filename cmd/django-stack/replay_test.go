package main

import (
	"bytes"
	"io"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"testing"
	"time"

	"github.com/vaibdix/django-stack/internal/livetest"
	"github.com/vaibdix/django-stack/internal/scaffold"
)

var replayMasks = []*regexp.Regexp{
	regexp.MustCompile(`SECRET_KEY=.*`),
	regexp.MustCompile(`"createdAt": "[^"]*"`),
	regexp.MustCompile(`Generated by Django [0-9.]+ on [0-9-]+ [0-9:]+`),
}

func TestAGeneratedProjectRegeneratesFromItsManifest(t *testing.T) {
	livetest.Require(t, "generate a real project twice")

	first, second := t.TempDir(), t.TempDir()
	answers := filepath.Join(first, "answers.json")
	if err := os.WriteFile(answers, []byte(`{"name": "replay", "python": "3.13", "django": "6.1.2",
		"database": "sqlite", "stack": "htmx", "app": "catalog", "addons": ["git", "ruff", "mypy"]}`), 0o644); err != nil {
		t.Fatal(err)
	}

	t.Chdir(first)
	if err := generateFromAnswers(answers, io.Discard, scaffold.Options{Clock: time.Now}); err != nil {
		t.Fatalf("first generation: %v", err)
	}
	t.Chdir(second)
	if err := generateFromAnswers(filepath.Join(first, "replay", "django-stack.json"), io.Discard, scaffold.Options{Clock: time.Now}); err != nil {
		t.Fatalf("generation from the manifest: %v", err)
	}

	a, b := projectFiles(t, filepath.Join(first, "replay")), projectFiles(t, filepath.Join(second, "replay"))
	if !slices.Equal(slices.Sorted(maps.Keys(a)), slices.Sorted(maps.Keys(b))) {
		t.Fatalf("the regenerated project has different files:\nfirst:  %v\nsecond: %v", slices.Sorted(maps.Keys(a)), slices.Sorted(maps.Keys(b)))
	}
	for name, content := range a {
		if !bytes.Equal(content, b[name]) {
			t.Errorf("%s differs between the original and the regenerated project", name)
		}
	}
}

func projectFiles(t *testing.T, root string) map[string][]byte {
	t.Helper()

	skip := []string{".venv", ".git", "__pycache__", ".mypy_cache", ".ruff_cache", "staticfiles", "node_modules"}
	files := map[string][]byte{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if slices.Contains(skip, d.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Name() == "db.sqlite3" {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, mask := range replayMasks {
			content = mask.ReplaceAll(content, []byte("<masked>"))
		}
		rel, err := filepath.Rel(root, path)
		files[rel] = content
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}
